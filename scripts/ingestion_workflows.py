#!/usr/bin/env python3
"""Generate thin workflows; guard scheduled rollout with GitHub native state."""
import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import yaml
from ingestion.registry import SOURCES


def filename(source):
    return 'ingest-' + source.replace('_', '-') + '.yml'


def remote_workflows():
    result = subprocess.run(['gh', 'api', '--paginate', '--slurp',
                             'repos/{owner}/{repo}/actions/workflows?per_page=100'],
                            check=True, capture_output=True, text=True)
    return {Path(w['path']).name: w for page in json.loads(result.stdout)
            for w in page['workflows']}


def verify_disabled(names):
    remote = remote_workflows()
    invalid = [filename(s) for s in names
               if remote.get(filename(s), {}).get('state') != 'disabled_manually']
    if invalid:
        raise ValueError('Not verified disabled_manually: ' + ', '.join(invalid))
    print(f'Verified {len(names)} source workflows disabled_manually.')


def schedules(names):
    config = yaml.safe_load((ROOT / 'config/ingestion-schedules.yaml').read_text())
    overrides = config.get('overrides', {})
    if set(overrides) - set(names):
        raise ValueError('Schedule overrides contain unknown or excluded sources')
    result = {}
    for i, name in enumerate(names):
        count = overrides.get(name, config['runs_per_month'])
        if type(count) is not int or not 1 <= count <= 28:
            raise ValueError('runs_per_month must be an integer in 1..28')
        # Slots span a 28-day month. Never schedule at the busy hour boundary.
        phase = i / len(names)
        slots = [((phase + n) * 28 / count) for n in range(count)]
        crons = []
        for slot in slots:
            day = 1 + int(slot)
            hour = int((slot % 1) * 24)
            minute = 7 + i * 17 % 47
            crons.append(f'{minute} {hour} {day} * *')
        result[name] = crons
    return result


def workflow(source, crons, scheduled):
    lines = ['# Generated by scripts/ingestion_workflows.py; do not edit.',
             f'name: Ingest {source}', 'on:', '  workflow_dispatch:']
    if scheduled:
        lines += ['  schedule:'] + [f"    - cron: '{cron}'" for cron in crons]
    lines += ['permissions:', '  contents: read', 'concurrency:',
              f'  group: ingestion-{source}', '  cancel-in-progress: false',
              'jobs:', '  ingest:', '    uses: ./.github/workflows/ingestion-runner.yml',
              '    with:', f'      source: {source}', '    secrets:']
    secrets = ['DATABASE_URL', 'AWS_ACCESS_KEY_ID', 'AWS_SECRET_ACCESS_KEY',
               'AWS_SESSION_TOKEN', 'S3_BUCKET']
    if source == 'litres':
        secrets += ['LITRES_SID']
    if source == 'milli_kitaphana':
        secrets += ['MILLI_KITAPHANA_' + s for s in
                    ('AES_RAW_KEY', 'AES_DEFAULT_IV', 'AES_SALT', 'PRIV_KEY', 'SIG_PREFIX')]
    lines += [f'      {s}: ${{{{ secrets.{s} }}}}' for s in secrets]
    if source in {'miras', 'miras_periodicals'}:
        lines += [f'      SOURCE_SESSION_JSON: ${{{{ secrets.{source.upper()}_SESSION_JSON }}}}']
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['generate', 'disable', 'verify'])
    parser.add_argument('--scheduled', action='store_true', help='Requires all remote source workflows disabled')
    args = parser.parse_args()
    names = sorted(s for s in SOURCES if s != 'common_crawl')
    if args.action == 'disable':
        for source in names:
            subprocess.run(['gh', 'workflow', 'disable', filename(source)], check=True)
        verify_disabled(names)
        return
    if args.action == 'verify':
        verify_disabled(names)
        return
    if args.scheduled:
        verify_disabled(names)
    slots = schedules(names)
    directory = ROOT / '.github/workflows'
    directory.mkdir(parents=True, exist_ok=True)
    obsolete = {p.name for p in directory.glob('ingest-*.yml')} - {filename(s) for s in names}
    if obsolete:
        raise ValueError('Retire obsolete source workflows explicitly: ' + ', '.join(sorted(obsolete)))
    table = ['# Source schedules', '',
             'Generated UTC slots; generated triggers are ' + ('scheduled.' if args.scheduled else '**manual only**.'), '',
             '| Source | Workflow | UTC cron slots |', '| --- | --- | --- |']
    for source in names:
        (directory / filename(source)).write_text(workflow(source, slots[source], args.scheduled))
        table.append(f"| {source} | {filename(source)} | {'; '.join('`' + c + '`' for c in slots[source])} |")
    (ROOT / 'docs/ingestion-schedules.md').write_text('\n'.join(table) + '\n')
    print(f'Generated {len(names)} source workflows; scheduled={args.scheduled}.')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        # Never print gh stderr or operational credentials.
        print(f'Workflow operation failed: {type(error).__name__}: {error}', file=sys.stderr)
        sys.exit(1)
